import { chromium } from '@playwright/test';
import fs from 'node:fs';
import sharp from 'sharp';
fs.mkdirSync('.artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: '.artifacts/home-desktop.png' });
await page.screenshot({ path: '.artifacts/home-full-original.png', fullPage: true });
await sharp('.artifacts/home-full-original.png').resize({ width: 1000 }).png().toFile('.artifacts/home-full.png');
console.log('DESKTOP', JSON.stringify(await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, heading: document.querySelector('h1')?.innerText, brokenImages: [...document.images].filter(i=>i.complete && i.naturalWidth===0).map(i=>i.src) }))));
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: '.artifacts/home-mobile.png' });
console.log('MOBILE', JSON.stringify(await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }))));
await page.getByRole('button', { name: 'Open navigation menu' }).click();
await page.screenshot({ path: '.artifacts/menu-mobile.png' });
await page.getByRole('button', { name: 'Close menu', exact: true }).click();
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto('http://localhost:3000/product/neon-raspberry-blast-ricordea', { waitUntil: 'networkidle' });
await page.screenshot({ path: '.artifacts/product-desktop.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: '.artifacts/product-mobile.png' });
console.log('PRODUCT MOBILE', JSON.stringify(await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }))));
console.log('BROWSER ERRORS', JSON.stringify(errors));
await browser.close();
